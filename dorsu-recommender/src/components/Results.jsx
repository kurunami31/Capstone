import { useState, useEffect } from 'react'
import programs from '../data/programs.json'
import generatePDF from './Report.jsx'
import ComparisonView from './ComparisonView.jsx'
import HollandChart from './HollandChart.jsx'
import RadarChart from './RadarChart.jsx'
import ScoreSimulator from './ScoreSimulator.jsx'
import ProgramDetailModal from './ProgramDetailModal.jsx'

function codeColor(score) {
  if (score >= 80) return '#34d399'
  if (score >= 60) return '#fbbf24'
  return '#f87171'
}

function admissionColor(level) {
  if (level === 'High') return '#34d399'
  if (level === 'Moderate') return '#fbbf24'
  return '#f87171'
}

function HeartIcon({ filled }) {
  return (
    <svg width="20" height="20" viewBox="0 0 24 24" fill={filled ? '#ef4444' : 'none'} stroke={filled ? '#ef4444' : '#64748b'} strokeWidth="2" strokeLinecap="round" strokeLinejoin="round">
      <path d="M20.84 4.61a5.5 5.5 0 0 0-7.78 0L12 5.67l-1.06-1.06a5.5 5.5 0 0 0-7.78 7.78l1.06 1.06L12 21.23l7.78-7.78 1.06-1.06a5.5 5.5 0 0 0 0-7.78z"/>
    </svg>
  )
}

export default function Results({ studentData, results, systemSettings, activePrograms, onRestart }) {
  const [selected, setSelected] = useState([])
  const [showCompare, setShowCompare] = useState(false)
  const [favorites, setFavorites] = useState(new Set())
  const [favLoading, setFavLoading] = useState(new Set())
  const [detailProgram, setDetailProgram] = useState(null)
  const [showSimulator, setShowSimulator] = useState(false)
  const [shareCopied, setShareCopied] = useState(false)

  const handleShareResults = async () => {
    const lines = ['DOrSU Program Recommender - My Results']
    lines.push(`Student: ${studentData.name} | School: ${studentData.school} | Strand: ${studentData.strand} | GWA: ${studentData.gwa}`)
    lines.push('')
    results.slice(0, 5).forEach((r, i) => {
      lines.push(`${i + 1}. ${r.program.name} (${r.totalScore}%) - ${r.program.faculty}`)
      lines.push(`   Academic: ${r.breakdown.academic}% | SUAST: ${r.breakdown.suast}% | Personal Fit: ${r.breakdown.personalFit}%`)
      lines.push(`   Admission: ${r.admission.label} (${r.admission.value})`)
      lines.push('')
    })
    lines.push('Generated by DOrSU Recommender System')
    try {
      await navigator.clipboard.writeText(lines.join('\n'))
      setShareCopied(true)
      setTimeout(() => setShareCopied(false), 2500)
    } catch {
      const textarea = document.createElement('textarea')
      textarea.value = lines.join('\n')
      document.body.appendChild(textarea)
      textarea.select()
      document.execCommand('copy')
      document.body.removeChild(textarea)
      setShareCopied(true)
      setTimeout(() => setShareCopied(false), 2500)
    }
  }

  useEffect(() => {
    fetch('/api/favorites', { credentials: 'include' })
      .then(r => r.json())
      .then(data => setFavorites(new Set(data.map(f => f.programCode))))
      .catch(() => {})
  }, [])

  const toggleFavorite = async (programCode) => {
    setFavLoading(prev => new Set(prev).add(programCode))
    const wasFav = favorites.has(programCode)
    setFavorites(prev => {
      const next = new Set(prev)
      wasFav ? next.delete(programCode) : next.add(programCode)
      return next
    })
    try {
      if (wasFav) {
        await fetch(`/api/favorites/${encodeURIComponent(programCode)}`, { method: 'DELETE', credentials: 'include' })
      } else {
        await fetch('/api/favorites', { method: 'POST', credentials: 'include', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ programCode }) })
      }
    } catch {
      setFavorites(prev => {
        const next = new Set(prev)
        wasFav ? next.add(programCode) : next.delete(programCode)
        return next
      })
    } finally {
      setFavLoading(prev => { const n = new Set(prev); n.delete(programCode); return n })
    }
  }

  const toggleSelect = (code) => {
    setSelected(prev =>
      prev.includes(code) ? prev.filter(c => c !== code) : [...prev, code]
    )
  }

  if (!results || results.length === 0) {
    return (
      <div style={{ textAlign: 'center', padding: 40 }}>
        <h2 style={{ color: '#f1f5f9' }}>No recommendations available</h2>
        <p style={{ color: '#64748b' }}>Please complete the assessment first.</p>
      </div>
    )
  }

  return (
    <div>
      <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'flex-start', marginBottom: 24, flexWrap: 'wrap', gap: 12 }}>
        <div>
          <h2 style={{ fontSize: 24, margin: 0, color: '#f1f5f9' }}>Your Top Program Matches</h2>
          <p style={{ color: '#94a3b8', margin: '4px 0 0 0', fontSize: 14 }}>
            {studentData.name} | {studentData.school} | {studentData.strand} Strand | GWA: {studentData.gwa}
          </p>
        </div>
        <div style={{ display: 'flex', gap: 8 }}>
          {selected.length >= 2 && (
            <button onClick={() => setShowCompare(true)} style={{
              padding: '10px 20px', fontSize: 14, fontWeight: 600,
              backgroundColor: 'rgba(99,102,241,0.15)', color: '#818cf8',
              border: '1px solid rgba(99,102,241,0.3)', borderRadius: 8, cursor: 'pointer',
            }}>
              Compare ({selected.length})
            </button>
          )}
          <button onClick={() => setShowSimulator(true)} style={simBtn}>Simulate</button>
          <button onClick={handleShareResults} style={shareBtn}>
            {shareCopied ? 'Copied!' : 'Share'}
          </button>
          <button onClick={() => generatePDF(studentData, results)} style={pdfBtn}>Download PDF</button>
          <button onClick={onRestart} style={restartBtn}>Start Over</button>
        </div>
      </div>

      <div style={{ display: 'grid', gap: 16 }}>
        {results.map((r) => (
          <div key={r.program.code} style={{
            border: '1px solid rgba(255,255,255,0.08)', borderRadius: 14, padding: 20,
            backgroundColor: 'rgba(255,255,255,0.04)', backdropFilter: 'blur(8px)',
          }}>
            <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', marginBottom: 12 }}>
              <div style={{ display: 'flex', alignItems: 'center', gap: 12 }}>
                <div style={{
                  width: 36, height: 36, borderRadius: '50%',
                  backgroundColor: codeColor(r.totalScore), color: '#0f172a',
                  display: 'flex', alignItems: 'center', justifyContent: 'center',
                  fontWeight: 700, fontSize: 16
                }}>
                  {r.rank}
                </div>
                <div>
                  <button onClick={() => setDetailProgram(r)} style={{
                    background: 'none', border: 'none', padding: 0, cursor: 'pointer',
                    fontWeight: 600, fontSize: 16, color: '#f1f5f9', textAlign: 'left',
                    fontFamily: 'inherit',
                  }}
                    onMouseEnter={e => e.currentTarget.style.color = '#60a5fa'}
                    onMouseLeave={e => e.currentTarget.style.color = '#f1f5f9'}
                  >
                    {r.program.name}
                  </button>
                  <div style={{ fontSize: 13, color: '#64748b' }}>{r.program.faculty}</div>
                </div>
              </div>
              <div style={{ display: 'flex', alignItems: 'center', gap: 10 }}>
                <button
                  onClick={() => toggleFavorite(r.program.code)}
                  disabled={favLoading.has(r.program.code)}
                  style={{
                    background: 'none', border: 'none', cursor: 'pointer',
                    padding: 4, display: 'flex', alignItems: 'center',
                    opacity: favLoading.has(r.program.code) ? 0.4 : 1,
                    transition: 'transform 0.15s',
                  }}
                  onMouseEnter={e => e.currentTarget.style.transform = 'scale(1.15)'}
                  onMouseLeave={e => e.currentTarget.style.transform = 'scale(1)'}
                  title={favorites.has(r.program.code) ? 'Remove from favorites' : 'Add to favorites'}
                >
                  <HeartIcon filled={favorites.has(r.program.code)} />
                </button>
                <label style={{
                  display: 'flex', alignItems: 'center', gap: 4, cursor: 'pointer',
                  fontSize: 11, color: selected.includes(r.program.code) ? '#818cf8' : '#64748b',
                  userSelect: 'none',
                }}>
                  <input
                    type="checkbox"
                    checked={selected.includes(r.program.code)}
                    onChange={() => toggleSelect(r.program.code)}
                    style={{ accentColor: '#6366f1', width: 14, height: 14, cursor: 'pointer' }}
                  />
                  Compare
                </label>
                <div style={{ textAlign: 'right' }}>
                  <div style={{ fontSize: 28, fontWeight: 700, color: codeColor(r.totalScore) }}>
                    {r.totalScore}%
                  </div>
                  <div style={{ fontSize: 12, color: '#64748b' }}>Overall Match</div>
                </div>
              </div>
            </div>

            <div style={{ display: 'flex', gap: 16, flexWrap: 'wrap', marginBottom: 12 }}>
              <div style={{ flex: 1, minWidth: 60 }}>
                <div style={statBox}>
                  <span style={statLabel}>Academic</span>
                  <span style={{ ...statValue, color: codeColor(r.breakdown.academic) }}>{r.breakdown.academic}%</span>
                </div>
              </div>
              <div style={{ flex: 1, minWidth: 60 }}>
                <div style={statBox}>
                  <span style={statLabel}>SUAST</span>
                  <span style={{ ...statValue, color: codeColor(r.breakdown.suast) }}>{r.breakdown.suast}%</span>
                </div>
              </div>
              <div style={{ flex: 1, minWidth: 60 }}>
                <div style={statBox}>
                  <span style={statLabel}>Personal Fit</span>
                  <span style={{ ...statValue, color: codeColor(r.breakdown.personalFit) }}>{r.breakdown.personalFit}%</span>
                </div>
              </div>
              <div style={{ flex: 1, minWidth: 100 }}>
                <div style={{
                  ...statBox, border: `2px solid ${admissionColor(r.admission.label)}`,
                  backgroundColor: `${admissionColor(r.admission.label)}15`
                }}>
                  <span style={statLabel}>Admission Chance</span>
                  <span style={{ ...statValue, color: admissionColor(r.admission.label) }}>
                    {r.admission.label}
                  </span>
                  <div style={{
                    marginTop: 6, height: 4, borderRadius: 2,
                    backgroundColor: 'rgba(255,255,255,0.06)', overflow: 'hidden',
                  }}>
                    <div style={{
                      width: r.admission.label === 'High' ? '85%' : r.admission.label === 'Moderate' ? '60%' : '35%',
                      height: '100%', borderRadius: 2,
                      backgroundColor: admissionColor(r.admission.label),
                      transition: 'width 0.5s ease',
                    }} />
                  </div>
                  <div style={{ fontSize: 10, color: '#64748b', marginTop: 2 }}>
                    {r.admission.value}
                  </div>
                </div>
              </div>
            </div>

            <div style={{ display: 'flex', gap: 6, flexWrap: 'wrap' }}>
            {r.program.ched_priority && (
              <div style={{ fontSize: 12, color: '#60a5fa', backgroundColor: 'rgba(59,130,246,0.1)', border: '1px solid rgba(59,130,246,0.15)', padding: '4px 10px', borderRadius: 4, display: 'inline-block' }}>
                CHED Priority Course
              </div>
            )}

            {studentData.hollandScores && Object.keys(studentData.hollandScores).length > 0 && (
              <div style={{ display: 'flex', alignItems: 'center', gap: 12, flexWrap: 'wrap' }}>
                <HollandChart scores={studentData.hollandScores} />
                <RadarChart scores={studentData.hollandScores} size={120} labels={{
                  R: 'Realistic', I: 'Investigative', A: 'Artistic',
                  S: 'Social', E: 'Enterprising', C: 'Conventional',
                }} colors={{
                  R: '#ef4444', I: '#3b82f6', A: '#f59e0b',
                  S: '#34d399', E: '#8b5cf6', C: '#ec4899',
                }} />
              </div>
            )}
              {r.program.is_board_program && (
                <div style={{ fontSize: 12, color: '#34d399', backgroundColor: 'rgba(52,211,153,0.1)', border: '1px solid rgba(52,211,153,0.15)', padding: '4px 10px', borderRadius: 4, display: 'inline-block' }}>
                  {r.program.board_exam ? `Licensure: ${r.program.board_exam}` : 'Board Program'}
                </div>
              )}
            </div>

            {r.program.career_paths && r.program.career_paths.length > 0 && (
              <div style={{ marginTop: 12 }}>
                <div style={{ fontSize: 12, color: '#64748b', marginBottom: 6, fontWeight: 600 }}>Career Paths</div>
                <div style={{ display: 'flex', gap: 6, flexWrap: 'wrap' }}>
                  {r.program.career_paths.map((career, ci) => (
                    <span key={ci} style={{
                      fontSize: 11, padding: '3px 10px', borderRadius: 20,
                      backgroundColor: 'rgba(20,184,166,0.1)', color: '#5eead4',
                      border: '1px solid rgba(20,184,166,0.2)',
                    }}>
                      {career}
                    </span>
                  ))}
                </div>
              </div>
            )}
          </div>
        ))}
      </div>

      {detailProgram && (
        <ProgramDetailModal
          result={detailProgram}
          studentData={studentData}
          onClose={() => setDetailProgram(null)}
        />
      )}
      {showCompare && (
        <ComparisonView
          results={results.filter(r => selected.includes(r.program.code))}
          onClose={() => setShowCompare(false)}
        />
      )}
      {showSimulator && (
        <ScoreSimulator
          studentData={studentData}
          programs={programs}
          systemSettings={systemSettings}
          activePrograms={activePrograms}
          onClose={() => setShowSimulator(false)}
        />
      )}
    </div>
  )
}

const statBox = {
  padding: '10px 14px', backgroundColor: 'rgba(255,255,255,0.04)', borderRadius: 10,
  border: '1px solid rgba(255,255,255,0.06)', textAlign: 'center',
}
const statLabel = { display: 'block', fontSize: 12, color: '#64748b', marginBottom: 4 }
const statValue = { display: 'block', fontWeight: 700, fontSize: 18 }

const simBtn = {
  padding: '10px 20px', fontSize: 14, fontWeight: 600,
  backgroundColor: 'rgba(168,85,247,0.15)', color: '#a78bfa',
  border: '1px solid rgba(168,85,247,0.3)', borderRadius: 8, cursor: 'pointer',
}
const shareBtn = {
  padding: '10px 20px', fontSize: 14, fontWeight: 600,
  backgroundColor: 'rgba(52,211,153,0.15)', color: '#34d399',
  border: '1px solid rgba(52,211,153,0.3)', borderRadius: 8, cursor: 'pointer',
}
const pdfBtn = {
  padding: '10px 24px', fontSize: 14, fontWeight: 600,
  backgroundColor: '#059669', color: '#fff',
  border: 'none', borderRadius: 8, cursor: 'pointer',
}
const restartBtn = {
  padding: '10px 24px', fontSize: 14, fontWeight: 600,
  backgroundColor: 'rgba(255,255,255,0.04)', color: '#94a3b8',
  border: '1px solid rgba(255,255,255,0.1)', borderRadius: 8, cursor: 'pointer',
}
